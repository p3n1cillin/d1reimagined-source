"""d1-social-tables.py - the compact tables the responder's social services read (stream I).

    python -I d1-social-tables.py --manifest DIR [--build DIR] [--out DIR]

Inputs (local only, never committed):
  --manifest  Bungie's final D1 manifest as DIM ships it: d1-manifest-base.json.gz and
              d1-manifest-strings-en.json.gz (DestinyVendorDefinition, DestinyActivityDefinition,
              DestinyInventoryItemDefinition, DestinyObjectiveDefinition, DestinyProgressionDefinition,
              DestinyInventoryBucketDefinition).
  --build     the 56578 tables the project generates from the owned packages
              (d1-oracle item-index write, d1-item-actions.py, d1-flagtable.py):
              item-content-index.tsv, item-actions.tsv, unlock-flags.tsv.
              Default: d1paths workspace()/capture-rig/builds/later-56578.
Committed inputs: ps4/fixtures/56578/vendor/vendor-sales.tsv (the client's vendor table, by row) and
ps4/fixtures/56578/characters/activity-table.tsv (activity index -> hash).

Outputs (--out, default ps4/d1-server/crates/d1-responder/data/social): derived facts only, a few
columns each, every file headed with its sources. No Bungie file is copied; names are kept only for
vendors, activities and progressions, as labels.

Joins and checks (exit 2 if one fails):
  * the client's vendor row N has the manifest vendor with the same hash, and the same sale count:
    then sale index N.k is manifest sale k (Eva's sale 23 is Command for 570 Glimmer in both);
  * an item's content index comes from the client's own item table (item-content-index.tsv);
  * an activity's completion flag row, kind and sub come from the client's flag table
    (unlock-flags.tsv); Restoration's completion is row 132, kind 3, sub 42.
"""
import argparse
import collections
import gzip
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)

FAILED = []


def check(ok, what):
    if not ok:
        FAILED.append(what)
        print(f'CONTROL FAILED: {what}', file=sys.stderr)


def tsv_rows(path, skip_hash=True):
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or (skip_hash and line.startswith('#')):
                continue
            yield line.split('\t')


def write(out, name, header_lines, columns, rows):
    path = os.path.join(out, name)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# GENERATED by tools/ps4_setup/d1-social-tables.py - do not hand-edit.\n')
        for h in header_lines:
            f.write(f'# {h}\n')
        f.write('\t'.join(columns) + '\n')
        for r in rows:
            f.write('\t'.join(str(x) for x in r) + '\n')
    print(f'{name}: {len(rows)} rows')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--manifest', required=True)
    ap.add_argument('--build')
    ap.add_argument('--out', default=os.path.join(REPO, 'ps4', 'd1-server', 'crates', 'd1-responder', 'data', 'social'))
    a = ap.parse_args()
    if not a.build:
        import d1paths
        a.build = str(d1paths.workspace() / 'capture-rig' / 'builds' / 'later-56578')
    os.makedirs(a.out, exist_ok=True)

    base = json.load(gzip.open(os.path.join(a.manifest, 'd1-manifest-base.json.gz')))
    strs = json.load(gzip.open(os.path.join(a.manifest, 'd1-manifest-strings-en.json.gz')))
    V, VS = base['DestinyVendorDefinition'], strs['DestinyVendorDefinition']
    I, IS = base['DestinyInventoryItemDefinition'], strs['DestinyInventoryItemDefinition']
    O = base['DestinyObjectiveDefinition']
    P = base['DestinyProgressionDefinition']
    A, AS = base['DestinyActivityDefinition'], strs['DestinyActivityDefinition']
    AT = base['DestinyActivityTypeDefinition']
    ATS = strs['DestinyActivityTypeDefinition']
    src_manifest = "Bungie's final D1 manifest (DIM's d1-manifest-base/strings-en.json.gz, local input)"

    # --- the client's tables -------------------------------------------------------------------
    content = {}
    for r in tsv_rows(os.path.join(a.build, 'item-content-index.tsv')):
        if r[0] == 'item_hash':
            continue
        content[int(r[0], 16)] = int(r[1])
    actions = {}
    for r in tsv_rows(os.path.join(a.build, 'item-actions.tsv')):
        if r[0] == 'content_index':
            continue
        actions[int(r[0])] = {'bucket': int(r[3]), 'tier': int(r[4]), 'instanced': r[5] == '1',
                              'action': r[6], 'reward_set': int(r[7]) if r[7].lstrip('-').isdigit() else -1}
    flags = {}
    for r in tsv_rows(os.path.join(a.build, 'unlock-flags.tsv')):
        if r[0] == 'index':
            continue
        flags[int(r[1])] = (int(r[0]), int(r[2]), int(r[3]))
    check(flags.get(3505060736) == (132, 3, 42), 'Restoration completion = flag row 132, kind 3, sub 42')
    check(content.get(3159615086) == 869, 'Glimmer (3159615086) is content 869')

    sales_tsv = os.path.join(REPO, 'ps4', 'fixtures', '56578', 'vendor', 'vendor-sales.tsv')
    client_vendor = {}
    client_sales = collections.defaultdict(dict)
    for r in tsv_rows(sales_tsv):
        if r[0] == 'vendor':
            continue
        v, s = int(r[0]), int(r[1])
        client_vendor[v] = int(r[2], 16)
        client_sales[v][s] = int(r[3])
    act_table = {}
    for r in tsv_rows(os.path.join(REPO, 'ps4', 'fixtures', '56578', 'characters', 'activity-table.tsv')):
        if r[0] == 'index':
            continue
        act_table[int(r[0])] = int(r[1], 16)

    # --- vendors -------------------------------------------------------------------------------
    vendors, rules, cats = [], [], []
    joined = {}
    for vi, vh in sorted(client_vendor.items()):
        v = V.get(str(vh))
        if v is None:
            continue
        if len(v['sales']) != len(client_sales[vi]):
            print(f'vendor {vi} {vh}: {len(client_sales[vi])} client sales vs {len(v["sales"])} in the manifest - not joined')
            continue
        # Positional join, checked by content: every sale's item must have the same content index.
        mism = sum(1 for k, x in enumerate(v['sales']) if content.get(x['itemHash']) != client_sales[vi].get(k))
        if mism:
            print(f'vendor {vi} {vh}: {mism} sales differ by content - not joined')
            continue
        joined[vi] = vh
        sm = v['summary']
        name = VS.get(str(vh), {}).get('summary', {}).get('vendorName', '?').replace('\t', ' ')
        refundable = sum(1 for x in v['sales'] if x.get('refundPolicy', 0))
        vendors.append((vi, f'{vh:#010x}', sm['resetIntervalMinutes'], sm['resetOffsetMinutes'],
                        sm['factionHash'], sm['progressionHash'], len(v['sales']), refundable,
                        sm.get('eventHash', 0), int(bool(sm.get('inhibitBuying'))), name))
        for k, x in enumerate(v['sales']):
            fm = 0
            for fi in x.get('failureIndexes') or []:
                fm |= 1 << fi
            rules.append((vi, k, x['categoryIndex'], x.get('refundPolicy', 0), x.get('refundLimit', 0),
                          x.get('requiredLevel', 0), fm))
        cstr = VS.get(str(vh), {}).get('categories') or []
        for ci, c in enumerate(v['categories']):
            title = ((cstr[ci] if ci < len(cstr) else None) or {}).get('displayTitle') or ''
            cats.append((vi, ci, c['quantityAvailable'], int(bool(c['hideFromRegularPurchase'])),
                         int(bool(c['hasOverlay'])), title.replace('\t', ' ')))
    check(joined.get(6) == 0x080760B4, 'client vendor 6 is the Guardian Outfitter (0x080760B4)')
    check(joined.get(12) == 3917130357, 'client vendor 12 is Eververse')
    check(joined.get(5) == 2796397637, 'client vendor 5 is Xur (Agent of the Nine)')
    hdr = [f'sources: {src_manifest}; ps4/fixtures/56578/vendor/vendor-sales.tsv (the client vendor table row = vendor)',
           'reset_interval / reset_offset in minutes (DestinyVendorSummary): resets fall where',
           '(unix_minutes + offset) mod interval == 0 (the weekly 10080/2340 lands on Tuesday 09:00 UTC).',
           'refundable = sales with refundPolicy != 0 (DestinyVendorItemRefundPolicy).']
    write(a.out, 'vendors.tsv', hdr, ['vendor', 'hash', 'reset_interval', 'reset_offset', 'faction', 'progression',
                                      'sales', 'refundable', 'event', 'inhibit_buying', 'name'], vendors)
    write(a.out, 'vendor-sale-rules.tsv',
          [f'sources: {src_manifest}, sales[] joined by position to the client vendor table (checked by content)',
           'refund_policy: 0 NotRefundable, 1 DeletesItem, 2 RevokesLicense; refund_limit in minutes;',
           'failure_mask: bit n = failureStrings[n] of the vendor applies.'],
          ['vendor', 'sale', 'category', 'refund_policy', 'refund_limit', 'required_level', 'failure_mask'], rules)
    write(a.out, 'vendor-categories.tsv',
          [f'sources: {src_manifest} (categories[], displayTitle)',
           'quantity: quantityAvailable, how many of the category\'s sales one refresh offers (0 = no limit).'],
          ['vendor', 'category', 'quantity', 'hide', 'overlay', 'title'], cats)

    # --- items: what inventory rules need --------------------------------------------------------
    items = []
    for h, ci in sorted(content.items(), key=lambda kv: kv[1]):
        d = I.get(str(h))
        act = actions.get(ci)
        if d is None or act is None:
            continue
        fl = (1 if d.get('nonTransferrable') else 0) | (2 if d.get('equippable') else 0) \
            | (4 if act['instanced'] else 0) | (8 if d.get('exclusive') else 0) \
            | (16 if d.get('uniquenessHash') else 0)
        items.append((ci, act['bucket'], d.get('tierType', 0), d.get('classType', 3), fl,
                      d.get('maxStackSize', 1), d.get('itemType', 0), act['action'], act['reward_set']))
    check(any(r[0] == 3598 and r[1] == 2 for r in items), 'the Khvostov (3598) is in bucket 2 (Primary Weapons)')
    write(a.out, 'items.tsv',
          [f'sources: {src_manifest} (tierType, classType, nonTransferrable, equippable, exclusive, maxStackSize,',
           'itemType); the client item table (content index) and action blocks (bucket = item definition +0x88,',
           'instanced = +0x8B, action, reward_set) from d1-item-actions.py.',
           'tier (manifest tierType): 2 Basic, 3 Common, 4 Rare, 5 Legendary, 6 Exotic; class: 0 Titan, 1 Hunter, 2 Warlock, 3 any;',
           'flags: 1 nonTransferrable, 2 equippable, 4 instanced, 8 exclusive, 16 uniquenessHash set (an equip-uniqueness group; set on 5,090 items, the Khvostov included).'],
          ['content', 'bucket', 'tier', 'class', 'flags', 'max_stack', 'item_type', 'action', 'reward_set'], items)

    # --- buckets: the client's ordinal for each manifest bucket, by the items in both ----------
    B, BS = base['DestinyInventoryBucketDefinition'], strs['DestinyInventoryBucketDefinition']
    votes = collections.defaultdict(collections.Counter)
    for h, ci in content.items():
        d = I.get(str(h))
        act = actions.get(ci)
        if d is None or act is None or act['bucket'] == 255:
            continue
        votes[act['bucket']][d.get('bucketTypeHash', 0)] += 1
    ordinal_of = {}
    brow = []
    for o in sorted(votes):
        (bh, n), = votes[o].most_common(1)
        total = sum(votes[o].values())
        bd = B.get(str(bh), {})
        ordinal_of.setdefault(bh, o)
        brow.append((o, bh, bd.get('bucketIdentifier', ''), bd.get('scope', -1), bd.get('itemCount', 0), n, total,
                     (BS.get(str(bh), {}).get('bucketName') or '').replace('	', ' ')))
    write(a.out, 'buckets.tsv',
          [f'sources: {src_manifest} (DestinyInventoryBucketDefinition) joined to the client bucket ordinal',
           '(item definition +0x88) by vote: of the items with that ordinal, `votes` of `items` have this manifest bucket.'],
          ['ordinal', 'hash', 'identifier', 'scope', 'item_count', 'votes', 'items', 'name'], brow)

    # --- bounties and quests -------------------------------------------------------------------
    rewards_progression = {}
    for h, d in I.items():
        n = (IS.get(h, {}).get('itemName') or '')
        if n.endswith(' Reputation') or n == 'Experience':
            rewards_progression[int(h)] = n
    bounties = []
    for h, d in I.items():
        ci = content.get(int(h))
        if ci is None or not d.get('objectiveHashes'):
            continue
        if d.get('itemType') not in (4, 12):  # 4 bounty, 12 quest step (DestinyItemType... per the manifest)
            continue
        objs = ';'.join(f"{o}:{O[str(o)]['completionValue']}" for o in d['objectiveHashes'] if str(o) in O)
        rw = ';'.join(f'{content.get(int(k), -1)}:{v}' for k, v in sorted(d.get('values', {}).items()))
        nxt = -1
        ql = d.get('questlineItemHash') or 0
        steps = I.get(str(ql), {}).get('setItemHashes') or []
        if int(h) in steps:
            i = steps.index(int(h))
            if i + 1 < len(steps):
                nxt = content.get(steps[i + 1], -1)
        bounties.append((ci, d['itemType'], objs or '-', rw or '-', nxt, content.get(ql, -1) if ql else -1))
    bounties.sort()
    write(a.out, 'bounties.tsv',
          [f'sources: {src_manifest}: items with objectives, itemType 4 (bounty) or 12 (quest step);',
           'objectives = objective hash:completionValue; rewards = content index of the reward item (values{}):amount,',
           'where -1 is a reward item the client table lacks; next = the questline\'s next step (setItemHashes).'],
          ['content', 'item_type', 'objectives', 'rewards', 'next', 'questline'], bounties)
    rp = []
    for h, n in sorted(rewards_progression.items()):
        ci = content.get(h)
        if ci is not None:
            rp.append((ci, f'{h}', n))
    write(a.out, 'reward-items.tsv',
          [f'sources: {src_manifest}: reward pseudo-items named "Experience" or "* Reputation" (item values{{}} keys).'],
          ['content', 'hash', 'name'], rp)
    prog = []
    want = {V[str(vh)]['summary']['progressionHash'] for vh in joined.values()} - {0}
    for ph in sorted(want):
        p = P.get(str(ph))
        if not p:
            continue
        prog.append((ph, p.get('name', ''), p.get('scope', 0), int(bool(p.get('repeatLastStep'))),
                     ','.join(str(s['progressTotal']) for s in p['steps'])))
    write(a.out, 'progressions.tsv',
          [f'sources: {src_manifest} (DestinyProgressionDefinition steps[].progressTotal) for vendor progressions.'],
          ['hash', 'name', 'scope', 'repeat_last', 'steps'], prog)

    # --- engrams (the Cryptarch's decode sales) -------------------------------------------------
    eng = []
    for vi, vh in joined.items():
        name = VS.get(str(vh), {}).get('summary', {}).get('vendorName')
        if name != 'Cryptarch':
            continue
        v = V[str(vh)]
        cstr = VS[str(vh)].get('categories') or []
        for k, x in enumerate(v['sales']):
            c = x['categoryIndex']
            t = ((cstr[c] if c < len(cstr) else None) or {}).get('displayTitle')
            if t != 'Decode Engram':
                continue
            d = I.get(str(x['itemHash']), {})
            ci = content.get(x['itemHash'])
            act = actions.get(ci, {})
            if ci is None:
                continue
            eng.append((vi, k, ci, d.get('tierType', 0), ordinal_of.get(d.get('bucketTypeHash'), -1), d.get('classType', 3)))
    eng.sort()
    write(a.out, 'engrams.tsv',
          [f'sources: {src_manifest}: the Cryptarchs\' "Decode Engram" sales (item = the engram, price = the engram);',
           "bucket = the client ordinal of the engram's manifest bucketTypeHash (see buckets.tsv), the slot it decodes into."],
          ['vendor', 'sale', 'engram', 'tier', 'bucket', 'class'], eng)

    # --- activities ----------------------------------------------------------------------------
    acts = []
    for idx, h in sorted(act_table.items()):
        d = A.get(str(h))
        if d is None:
            continue
        row, kind, sub = flags.get(d.get('completionFlagHash') or -1, (-1, -1, -1))
        tname = ATS.get(str(d.get('activityTypeHash')), {}).get('activityTypeName', '')
        name = AS.get(str(h), {}).get('activityName', '').replace('\t', ' ')
        acts.append((idx, f'{h:#010x}', d.get('activityLevel', 0), d.get('tier', 0), d.get('activityTypeHash', 0),
                     d.get('destinationHash', 0), row, kind, sub, int(bool(d.get('isMatchmade'))),
                     int(bool(d.get('isPlaylist'))), tname.replace('\t', ' '), name))
    check(any(r[0] == 166 and r[6] == 132 and r[8] == 42 for r in acts), 'activity 166 (Restoration) completes sub 42')
    write(a.out, 'activities.tsv',
          [f'sources: {src_manifest} (activityLevel, tier, activityTypeHash, destinationHash, completionFlagHash,',
           'isMatchmade, isPlaylist); ps4/fixtures/56578/characters/activity-table.tsv (index); the client flag table',
           '(completion row, kind, sub: kind 3 lives in the profile completion record, one byte per sub).'],
          ['index', 'hash', 'level', 'tier', 'type', 'destination', 'completion_row', 'kind', 'sub', 'matchmade',
           'playlist', 'type_name', 'name'], acts)

    # --- dismantle reward sets -------------------------------------------------------------------
    sets = collections.Counter()
    shape = {}
    for ci, act in actions.items():
        if act['action'] != 'shard':
            continue
        sets[act['reward_set']] += 1
        shape.setdefault(act['reward_set'], collections.Counter())[(act['tier'], act['bucket'])] += 1
    ds = []
    for rs, n in sorted(sets.items()):
        (tier, bucket), _ = shape[rs].most_common(1)[0]
        ds.append((rs, n, tier, bucket))
    write(a.out, 'dismantle-sets.tsv',
          ['sources: the client item action blocks (d1-item-actions.py): reward set u16 of every "shard" (dismantle) row,',
           'with how many items use it and the most common (client tier byte, bucket) among them. The amounts are not in the',
           'client data; the responder keeps them in a labelled placeholder table.'],
          ['reward_set', 'items', 'tier', 'bucket'], ds)

    if FAILED:
        sys.exit(2)


if __name__ == '__main__':
    main()
