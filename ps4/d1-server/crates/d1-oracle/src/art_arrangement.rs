//! ⭐ **THE ART-ARRANGEMENT GENERATOR** - `item content index -> the u16 that names its 3D model`,
//! plus the equipped-array ordinal, the stat-curve offset and the stat list.
//!
//! Port of `capture-rig/oodle/art-arrangement.py`. The consumer of what this writes is
//! [`crate::item_index::ArtTable`]; this module is the measurement, that one is the reader.
//!
//! # Why the number exists
//!
//! The character render description builder `FUN_0054CF70` fills four `u64` geometry handles per
//! equipment slot at `out + 0x188 + slot*0x20`, pre-initialised to `-1` = *no geometry*. Per slot of
//! the appearance block's 20 x 64 B equipment array (`0x80801855` field [6] @`+0x1E8`, element
//! `0x8080183C`) the gate is:
//!
//! 1. element `+0x08` u16 content index `!= 0xFFFF`, and the definition resolves
//!    (`vtbl[0x410]` = `0x25ADE0`, which also requires the item's world tag **loaded**), and
//! 2. the definition's gear record exists (`def+0x60` self-relative, non-zero), and
//! 3. ⭐ element `+0x0C` u16 - **the art-arrangement index** - resolves in the arrangement table
//!    (`FUN_0054B530`: bounds-checked `index < count`, 24-byte-stride content table).
//!    `0xFFFF` sign-extends to `-1`, fails the bound, and is the clean *no art* skip.
//!    ⛔ **`0` is IN RANGE** and silently names arrangement #0 - which is what every card fixture
//!    before 2026-08-10 shipped in all 20 slots.
//!
//! The class-correct value is content data: `FUN_00289E80(gear_record, class)` walks the record at
//! `def+0x60` - `{i64 count @+0, i64 self-rel @+8 -> entries at +0x10, stride 4:
//! {i8 class, u8 pad, u16 arrangement}}` - taking the first entry whose class byte is `-1`
//! (wildcard) or `== class`, skipping entries whose arrangement is `-1`. [`walk_289e80`] is that
//! walk, transliterated, against the definition bytes read out of the **packages**. No live client
//! is involved.
//!
//! # The guards are the valuable lines
//!
//! Every bounds check in the Python is carried across unchanged, including the exact comparison
//! (`<` vs `<=`) each one uses. They are what stops a self-relative offset that escapes the entry
//! from producing a plausible `u16`. So is the **identity check**: the definition entry carries the
//! item's own hash at `+0x78`, and a mismatch stops the tool rather than yielding a number for the
//! wrong item.
//!
//! # Reach
//!
//! `static-client-inference` (the walk) over package bytes. Nothing here is `observed-live`; the
//! discriminator is a boot with the rebuilt card served.

