use crate::profile::Control;

fn ok(name: &'static str, detail: impl Into<String>) -> Control {
    Control { name, pass: true, detail: detail.into() }
}
fn no(name: &'static str, detail: impl Into<String>) -> Control {
    Control { name, pass: false, detail: detail.into() }
}

/// Every control `art-arrangement.py --controls` shipped, carried across. **Exit 2 if any fails.**
///
/// Two are **inverted**: the same walk from a base two bytes off must NOT reproduce the pin, and
/// nor must the curve offset read two bytes late. Those are the checks that distinguish a
/// measurement from a coincidence.
pub fn controls() -> Vec<Control> {
    let table = match IndexTable::load_default() {
        Ok(t) => t,
        Err(e) => return vec![no("index-table", e.to_string())],
    };
    if !crate::oodle::default_pkgdir().is_dir() {
        return vec![no(
            "estate",
            format!("{} is absent - nothing here ran", crate::oodle::default_pkgdir().display()),
        )];
    }
    let mut c = match Content::open_default() {
        Ok(c) => c,
        Err(e) => return vec![no("estate", e.to_string())],
    };
    let mut v = Vec::new();

    // C1-C3: the identity hash on three entries with three different shapes. `resolve` itself
    // refuses an identity mismatch, so reaching a value here IS the identity check passing.
    let mut defs = std::collections::BTreeMap::new();
    for (ci, want_gear) in [(GJALLARHORN, true), (STRIKER, false), (BRONZE_TIER, false)] {
        match resolve(&mut c, ci, &table) {
            Ok(r) => {
                v.push(ok(
                    "identity-hash",
                    format!(
                        "ci {ci}: entry {:#010x} carries its own item hash {:#010x} at +0x78",
                        r.world_tag, r.item_hash
                    ),
                ));
                let got = r.gear.is_some();
                v.push(if got == want_gear {
                    ok("gear-record", format!(
                        "ci {ci}: def+0x60 {} (expected {})",
                        if got { "present" } else { "NULL" },
                        if want_gear { "present" } else { "NULL - no geometry" }))
                } else {
                    no("gear-record", format!(
                        "ci {ci}: def+0x60 {} but expected {}",
                        if got { "present" } else { "NULL" },
                        if want_gear { "present" } else { "NULL" }))
                });
                defs.insert(ci, r);
            }
            Err(e) => v.push(no("identity-hash", format!("ci {ci}: {e}"))),
        }
    }
    let Some(gjal) = defs.get(&GJALLARHORN).cloned() else {
        v.push(no("gjallarhorn", "the anchor item did not resolve - nothing below could run"));
        return v;
    };

    // C4: the pinned Gjallarhorn arrangement, all three classes (one wildcard entry).
    let all_pinned = gjal.per_class.iter().all(|a| *a == Some(GJALLARHORN_ARRANGEMENT));
    v.push(if all_pinned {
        ok("gjallarhorn-arrangement", format!(
            "per-class {:?} - the wildcard entry answers every class with \
             {GJALLARHORN_ARRANGEMENT}", gjal.per_class))
    } else {
        no("gjallarhorn-arrangement", format!(
            "per-class {:?}, want {GJALLARHORN_ARRANGEMENT} for all three", gjal.per_class))
    });

    // C5 INVERTED: the same walk from a base two bytes off must NOT reproduce the pin.
    let inv = (|| -> Result<String> {
        let (_p, _i, _cl, d) = c.entry_bytes_for_tag(gjal.world_tag)?;
        let g = gjal.gear.ok_or_else(|| OracleError::Shape("no gear record".into()))?;
        let shifted = walk_289e80(&d, g + 2, 1).ok().flatten();
        if shifted == Some(GJALLARHORN_ARRANGEMENT) {
            Err(OracleError::Shape(
                "the walk from gear+2 returned the SAME arrangement - the number does not depend on \
                 the base being right, so it is not a measurement"
                    .into(),
            ))
        } else {
            Ok(format!(
                "walk from gear+2 gives {shifted:?}, not {GJALLARHORN_ARRANGEMENT} - the number \
                 depends on the base being right"
            ))
        }
    })();
    v.push(match inv {
        Ok(d) => ok("NEGATIVE-shifted-base-differs", d),
        Err(e) => no("NEGATIVE-shifted-base-differs", e.to_string()),
    });

    // C6-C7 ⭐ the def+0x68 STAT LIST. Two shapes discriminate the walk from garbage: Gjallarhorn's
    // is NULL (rel == 0), Striker's is PRESENT but EMPTY (rel != 0, count 0). A shifted or misread
    // base raises on the count bound instead of producing either.
    v.push(if gjal.stats.is_none() {
        ok("stat-list-gjallarhorn-NULL",
           format!("ci {GJALLARHORN} def+0x68 is NULL - the client's own constructor FUN_0026E0E0 \
                    writes nothing into +0x88/+0x98"))
    } else {
        no("stat-list-gjallarhorn-NULL",
           format!("ci {GJALLARHORN} def+0x68 = {:?}, want NULL", gjal.stats))
    });
    match defs.get(&STRIKER) {
        Some(rs) if rs.stats.as_deref() == Some(&[]) => v.push(ok(
            "stat-list-striker-present-empty",
            format!("ci {STRIKER} def+0x68 is PRESENT with count 0 - the two shapes together pin \
                     the walk"))),
        Some(rs) => v.push(no("stat-list-striker-present-empty",
            format!("ci {STRIKER} def+0x68 = {:?}, want a present, empty list", rs.stats))),
        None => v.push(no("stat-list-striker-present-empty", "ci 710 did not resolve")),
    }

    // C8-C9 ⭐ the def+0x30 CURVE OFFSET. Oryx Mask is the one staged item with a nonzero value;
    // Gjallarhorn's record is PRESENT with value 0, which discriminates "present, 0" from
    // "absent -> 0".
    let oryx = resolve(&mut c, ORYX_MASK, &table);
    match &oryx {
        Ok(r) if r.curve_offset == (true, ORYX_MASK_CURVE) => v.push(ok(
            "curve-offset-oryx-mask",
            format!("ci {ORYX_MASK} def+0x30 rec+8 = {ORYX_MASK_CURVE}"))),
        Ok(r) => v.push(no("curve-offset-oryx-mask", format!(
            "ci {ORYX_MASK} def+0x30 rec+8 = {:?}, want (true, {ORYX_MASK_CURVE})", r.curve_offset))),
        Err(e) => v.push(no("curve-offset-oryx-mask", e.to_string())),
    }
    v.push(if gjal.curve_offset == (true, 0) {
        ok("curve-offset-gjallarhorn-present-zero", format!(
            "ci {GJALLARHORN} def+0x30 is PRESENT with offset 0 - so 0 is a measurement here, not a \
             default"))
    } else {
        no("curve-offset-gjallarhorn-present-zero", format!(
            "ci {GJALLARHORN} def+0x30 = {:?}, want (true, 0)", gjal.curve_offset))
    });

    // C10 INVERTED: the curve offset read two bytes late must NOT reproduce the pin.
    if let Ok(r) = &oryx {
        let inv = (|| -> Result<String> {
            let (_p, _i, _cl, d) = c.entry_bytes_for_tag(r.world_tag)?;
            let rel = i64_at(&d, 0x30)?;
            let at = 0x30 + rel + 8 + 2;
            if !(at >= 0 && at <= d.len() as i64 - 2) {
                return Ok(format!("rec30+10 is off the end of the entry - changed, as required"));
            }
            let shifted = u16_at(&d, at as usize)?;
            if shifted == ORYX_MASK_CURVE {
                Err(OracleError::Shape(format!(
                    "the u16 at rec30+10 is ALSO {ORYX_MASK_CURVE} - the value does not depend on \
                     the offset being right"
                )))
            } else {
                Ok(format!(
                    "u16 at rec30+10 is {shifted}, not {ORYX_MASK_CURVE} - the value depends on the \
                     offset being right"
                ))
            }
        })();
        v.push(match inv {
            Ok(d) => ok("NEGATIVE-curve-shifted-base-differs", d),
            Err(e) => no("NEGATIVE-curve-shifted-base-differs", e.to_string()),
        });
    }

    // C11 ⭐ the equipped-array ordinal, anchored on the one slot measured by a SECOND instrument:
    // the emblem definition (ci 1512) must name slot 12 - the byte a snapshot replay of
    // `investment_globals->vtbl[0x160]()[0x18]` independently returned.
    match resolve(&mut c, EMBLEM_INDEX, &table) {
        Ok(e) if e.equip_slot == Some(EMBLEM_SLOT as u8) => v.push(ok(
            "emblem-equip-slot",
            format!("ci {EMBLEM_INDEX} def_client+0x18 = {EMBLEM_SLOT}, the replayed emblem slot - \
                     two instruments, one byte"))),
        Ok(e) => v.push(no("emblem-equip-slot", format!(
            "ci {EMBLEM_INDEX} def_client+0x18 = {:?}, want {EMBLEM_SLOT}", e.equip_slot))),
        Err(e) => v.push(no("emblem-equip-slot", e.to_string())),
    }

    // C12: the consumer's own anchors, which is where a generator drift would land.
    v.push(if gjal.per_class[1] == Some(PINNED_ARRANGEMENT.1)
        && PINNED_ARRANGEMENT.0 == GJALLARHORN
        && PINNED_CURVE_OFFSET == (ORYX_MASK, ORYX_MASK_CURVE as i16)
    {
        ok("generator-agrees-with-the-consumers-pins", format!(
            "item_index::PINNED_ARRANGEMENT {PINNED_ARRANGEMENT:?} and PINNED_CURVE_OFFSET \
             {PINNED_CURVE_OFFSET:?} are what this generator measures"))
    } else {
        no("generator-agrees-with-the-consumers-pins", format!(
            "the generator measures ci {GJALLARHORN} -> {:?} / ci {ORYX_MASK} -> \
             {ORYX_MASK_CURVE}, the consumer pins {PINNED_ARRANGEMENT:?} / {PINNED_CURVE_OFFSET:?}",
            gjal.per_class[1]))
    });

    v
}

