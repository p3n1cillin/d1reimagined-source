pub const GENERATOR: &str = "d1-oracle art-arrangement --staged --write";

/// The reserved emblem content index (The Reflective Proof); the card always carries it at slot 12.
pub const EMBLEM_INDEX: u16 = 1512;

/// The item hash the definition entry carries at this offset - the identity check.
pub const DEF_IDENTITY_HASH: usize = 0x78;

// ── pinned anchors, all asserted by `controls` ───────────────────────────────────────────────────
/// Weapon: a gear record with ONE wildcard entry.
pub const GJALLARHORN: u16 = 6299;
pub const GJALLARHORN_ARRANGEMENT: u16 = 1229;
/// Subclass: NO gear record (`def+0x60 == 0`).
pub const STRIKER: u16 = 710;
/// `Bronze Tier`, `hasGeometry:false`: NO gear record.
pub const BRONZE_TIER: u16 = 1;
/// Helmet: the ONE staged item whose `def+0x30` curve offset is nonzero.
pub const ORYX_MASK: u16 = 6488;
pub const ORYX_MASK_CURVE: u16 = 70;

/// Everything one definition says about how the client will build and render the item.
#[derive(Debug, Clone)]
pub struct ItemDefinition {
    pub content_index: u16,
    pub item_hash: u32,
    pub world_tag: u32,
    /// Offset of the gear record within the entry, or `None` when `def+0x60` is NULL.
    pub gear: Option<usize>,
    /// Every `(class, arrangement)` entry of the gear record, in order.
    pub entries: Vec<(i8, u16)>,
    /// [`walk_289e80`]'s answer for classes 0, 1, 2.
    pub per_class: [Option<u16>; 3],
    /// `def_client+0x18`, or `None` when the definition has no client record.
    pub equip_slot: Option<u8>,
    /// `def+0x68`'s stat list. `None` = the def carries none; `Some(vec![])` = present but empty.
    /// The client's own constructor writes nothing into element `+0x88`/`+0x98` in either case, so
    /// the distinction is provenance, not behaviour - and it must stay visible.
    pub stats: Option<Vec<(u16, u32)>>,
    /// `(record present, value)` from `def+0x30`. An absent record leaves the schema default.
    pub curve_offset: (bool, u16),
    /// ⭐ `def_client+0x1C8` (u16) - the item's **weapon object index** ([`weapon_object`]), or
    /// `None` when the definition has no client record.
    pub weapon_object: Option<u16>,
}

fn i64_at(d: &[u8], o: usize) -> Result<i64> {
    d.get(o..o + 8)
        .map(|b| i64::from_le_bytes(b.try_into().unwrap()))
        .ok_or_else(|| OracleError::Shape(format!("i64 at +{o:#x} is past the {} byte entry", d.len())))
}
fn u16_at(d: &[u8], o: usize) -> Result<u16> {
    d.get(o..o + 2)
        .map(|b| u16::from_le_bytes(b.try_into().unwrap()))
        .ok_or_else(|| OracleError::Shape(format!("u16 at +{o:#x} is past the {} byte entry", d.len())))
}
fn u32_at(d: &[u8], o: usize) -> Result<u32> {
    d.get(o..o + 4)
        .map(|b| u32::from_le_bytes(b.try_into().unwrap()))
        .ok_or_else(|| OracleError::Shape(format!("u32 at +{o:#x} is past the {} byte entry", d.len())))
}

/// Resolve a self-relative `i64` at `base` into an absolute offset, without wrapping.
fn self_rel(base: usize, rel: i64) -> Option<i64> {
    (base as i64).checked_add(rel)
}

/// Offset of the definition's **gear record**, or `None`. `def+0x60` is a self-relative `i64`.
pub fn gear_record(d: &[u8]) -> Result<Option<usize>> {
    if d.len() < 0x80 {
        return Err(OracleError::Shape(format!(
            "definition entry is only {} bytes - not a definition",
            d.len()
        )));
    }
    let rel = i64_at(d, 0x60)?;
    if rel == 0 {
        return Ok(None);
    }
    let at = self_rel(0x60, rel)
        .ok_or_else(|| OracleError::Shape(format!("def+0x60 self-relative {rel:#x} overflows")))?;
    if !(at >= 0 && at < d.len() as i64 - 0x10) {
        return Err(OracleError::Shape(format!(
            "def+0x60 self-relative {rel:#x} escapes the {}-byte entry",
            d.len()
        )));
    }
    Ok(Some(at as usize))
}

/// ⭐ The item's **equipped-array ordinal** - `def_client + 0x18` (u8), where
/// `def_client = def + 0x18 + *(i64*)(def+0x18)`.
///
/// `0x269080` derefs `character + 0x2B80 + slot*8` with THIS byte: the item's own definition names
/// which of the 20 equipped/equipment entries it occupies. Cross-checked by the emblem control -
/// content index 1512's definition must say **12**, the independently replayed
/// [`crate::item_index::EMBLEM_SLOT`]. `None` when the definition has no client record.
pub fn equip_slot(d: &[u8]) -> Result<Option<u8>> {
    let rel = i64_at(d, 0x18)?;
    if rel == 0 {
        return Ok(None);
    }
    let dc = self_rel(0x18, rel)
        .ok_or_else(|| OracleError::Shape(format!("def_client self-relative {rel:#x} overflows")))?;
    if !(dc >= 0 && dc <= d.len() as i64 - 0x20) {
        return Err(OracleError::Shape(format!(
            "def_client self-relative {rel:#x} escapes the {}-byte entry",
            d.len()
        )));
    }
    Ok(Some(d[dc as usize + 0x18]))
}

/// Offset of the weapon object index inside the definition's client record.
pub const DEF_CLIENT_WEAPON_OBJECT: usize = 0x1C8;

/// ⭐ The item's **weapon object index** - `def_client + 0x1C8` (u16), the value equipment element
/// `+0x0A` must carry.
///
/// Build 56578 (14 Oct 2026): the player-configuration builder `0x912240` calls `0x910C60` once
/// per weapon slot. `0x910C60` reads element `+0x0A`, indexes the 208-entry table behind
/// `investment_globals+0x350` (tag `0x80A5FFA9`, 32-byte records) with it, and resolves the
/// record's name hash (`0x33FC20`) to the object-definition tag the loadout method `0x668D80`
/// then constructs at spawn. Element `+0x0A = 0` (every fixture before this) names record 0 ->
/// tag `0x80A7E218`, a type-8 object, so all three weapons spawned as non-weapons and the
/// player held only the Ghost. Serving this field (12/13/39 for the staged primary, special and
/// heavy) gave type-11 tags `0x80A6A02E`/`0x80A6A035`/`0x80A6A017` and a drawn hand cannon with
/// the weapon HUD. `None` when the definition has no client record.
pub fn weapon_object(d: &[u8]) -> Result<Option<u16>> {
    let rel = i64_at(d, 0x18)?;
    if rel == 0 {
        return Ok(None);
    }
    let dc = self_rel(0x18, rel)
        .ok_or_else(|| OracleError::Shape(format!("def_client self-relative {rel:#x} overflows")))?;
    let at = dc + DEF_CLIENT_WEAPON_OBJECT as i64;
    if dc < 0 {
        return Err(OracleError::Shape(format!("def_client self-relative {rel:#x} is negative")));
    }
    // Armor and other non-weapon definitions are shorter (546 B against a weapon's 776 B): their
    // client record ends before +0x1C8, which means "no weapon object", not a malformed entry.
    if at > d.len() as i64 - 2 {
        return Ok(None);
    }
    Ok(Some(u16_at(d, at as usize)?))
}

/// ⭐ The definition's **stat list** at `def+0x68` - the record `FUN_0028B6E0` (called by the
/// client's own element default-constructor `FUN_0026E0E0`, gated on `*(i64*)(def+0x68) != 0`)
/// copies into element `+0x88` (u16 stat indices) / `+0x98` (u32 values):
///
/// ```text
/// rec = def + 0x68 + *(i64*)(def+0x68)         // self-relative, 0 = NO LIST
/// count = *(i64*)(rec) ; rel = *(i64*)(rec+8)
/// entry i: u16 stat_index @ rec+8 + rel + 0x10 + i*8, u32 value @ +4 further
/// ```
///
/// (`b6e0`'s `rec + rec[+8] + i*8 + 0x18` and `cbb0`'s `(rec+8) + rec[+8] + i*8 + 0x10` are the same
/// address - two readers, one arithmetic.)
///
/// `None` = the def carries NO list; `Some(vec![])` = it carries an EMPTY one. The constructor
/// writes nothing either way, and the two shapes together are what pin the walk.
pub fn stat_list(d: &[u8]) -> Result<Option<Vec<(u16, u32)>>> {
    Ok(stat_pairs(d, 0x68, false)?.map(|pairs| {
        pairs.into_iter().map(|(key, value)| (key as u16, value)).collect()
    }))
}

/// Base investment stats at `def+0x50`, distinct from the optional instance defaults at +0x68.
/// Both records use the same self-relative list, but base keys occupy the full u32.
pub fn base_stat_list(d: &[u8]) -> Result<Option<Vec<(u32, u32)>>> {
    stat_pairs(d, 0x50, true)
}

fn stat_pairs(d: &[u8], field: usize, wide_key: bool) -> Result<Option<Vec<(u32, u32)>>> {
    let rel = i64_at(d, field)?;
    if rel == 0 {
        return Ok(None);
    }
    let rec = self_rel(field, rel)
        .ok_or_else(|| OracleError::Shape(format!("def+{field:#x} self-relative {rel:#x} overflows")))?;
    if !(rec >= 0 && rec < d.len() as i64 - 0x10) {
        return Err(OracleError::Shape(format!(
            "def+{field:#x} self-relative {rel:#x} escapes the {}-byte entry",
            d.len()
        )));
    }
    let rec = rec as usize;
    let cnt = i64_at(d, rec)?;
    if !(0..=64).contains(&cnt) {
        return Err(OracleError::Shape(format!(
            "stat count {cnt} is not a small array - wrong base"
        )));
    }
    let base = rec + 8;
    let rel2 = i64_at(d, base)?;
    let mut out = Vec::with_capacity(cnt as usize);
    for i in 0..cnt {
        let at = (base as i64)
            .checked_add(rel2)
            .and_then(|x| x.checked_add(0x10 + i * 8))
            .ok_or_else(|| OracleError::Shape(format!("stat entry {i} offset overflows")))?;
        if !(at >= 0 && at <= d.len() as i64 - 8) {
            return Err(OracleError::Shape(format!(
                "stat entry {i} at +{at:#x} escapes the entry"
            )));
        }
        let key = if wide_key { u32_at(d, at as usize)? } else { u16_at(d, at as usize)? as u32 };
        out.push((key, u32_at(d, at as usize + 4)?));
    }
    Ok(Some(out))
}

/// ⭐ The element's `+0x20` **stat-curve index offset**, as the client's own constructor sets it:
/// `FUN_0026E0E0` reads `*(u16*)(rec30 + 8)` where `rec30 = def + 0x30 + *(i64*)(def+0x30)` and
/// stores it at element `+0x20` (`*(u16*)(param_3 + 4*8)`). `FUN_002816F0` samples the stat-group
/// curve at `+0x20 + level`, so a wrong value here shifts every curve-derived stat.
///
/// Returns `(present, value)`. An absent record is `(false, 0)`: the constructor then keeps the
/// schema-default template byte, which is 0 `[I]`.
pub fn curve_offset(d: &[u8]) -> Result<(bool, u16)> {
    let rel = i64_at(d, 0x30)?;
    if rel == 0 {
        return Ok((false, 0));
    }
    let rec = self_rel(0x30, rel)
        .ok_or_else(|| OracleError::Shape(format!("def+0x30 self-relative {rel:#x} overflows")))?;
    if !(rec >= 0 && rec <= d.len() as i64 - 0x10) {
        return Err(OracleError::Shape(format!(
            "def+0x30 self-relative {rel:#x} escapes the {}-byte entry",
            d.len()
        )));
    }
    Ok((true, u16_at(d, rec as usize + 8)?))
}

/// `FUN_00289E80`, transliterated: the first entry whose class is `-1` or `== cls`, skipping
/// entries whose arrangement is `-1`. `None` when the walk runs off the end of the array.
pub fn walk_289e80(d: &[u8], gear: usize, cls: i8) -> Result<Option<u16>> {
    let cnt = i64_at(d, gear)?;
    if !(0..=64).contains(&cnt) {
        return Err(OracleError::Shape(format!(
            "gear count {cnt} is not a small array - wrong base"
        )));
    }
    let base = gear + 8;
    let rel = i64_at(d, base)?;
    let mut i: i64 = 0;
    loop {
        let at = loop {
            if i >= cnt {
                return Ok(None);
            }
            let at = (base as i64)
                .checked_add(rel)
                .and_then(|x| x.checked_add(0x10 + i * 4))
                .ok_or_else(|| OracleError::Shape(format!("gear entry {i} offset overflows")))?;
            if !(at >= 0 && at <= d.len() as i64 - 4) {
                return Err(OracleError::Shape(format!(
                    "gear entry {i} at +{at:#x} escapes the entry"
                )));
            }
            let c = d[at as usize] as i8;
            if c == -1 || c == cls {
                break at as usize;
            }
            i += 1;
        };
        let a = u16_at(d, at + 2)?;
        i += 1;
        if a != 0xFFFF {
            return Ok(Some(a));
        }
    }
}

/// ⭐ One content index -> everything its definition says. **Refuses a wrong entry.**
///
/// The definition is found by world tag (`item-content-index.tsv` column 3), and the entry's own
/// bytes carry the item hash at `+0x78` - so a wrong entry cannot produce a plausible number.
pub fn resolve(content: &mut Content, ci: u16, table: &IndexTable) -> Result<ItemDefinition> {
    let (item_hash, world_tag) = table.by_index(ci).ok_or_else(|| {
        OracleError::Shape(format!("content index {ci} is not in {}", table.path.display()))
    })?;
    let (_pkg, _idx, _class, d) = content.entry_bytes_for_tag(world_tag)?;
    let got = u32_at(&d, DEF_IDENTITY_HASH)?;
    if got != item_hash {
        return Err(OracleError::Shape(format!(
            "IDENTITY CHECK FAILED: entry {world_tag:#010x} carries hash {got:#010x} at \
             +{DEF_IDENTITY_HASH:#x}, the index table says {item_hash:#010x} - wrong entry, nothing \
             here may be used"
        )));
    }
    let gear = gear_record(&d)?;
    let mut entries = Vec::new();
    let mut per_class = [None, None, None];
    if let Some(g) = gear {
        let cnt = i64_at(&d, g)?;
        let rel = i64_at(&d, g + 8)?;
        for i in 0..cnt.max(0) {
            let at = (g as i64 + 8)
                .checked_add(rel)
                .and_then(|x| x.checked_add(0x10 + i * 4))
                .ok_or_else(|| OracleError::Shape(format!("gear entry {i} offset overflows")))?;
            if !(at >= 0 && at <= d.len() as i64 - 4) {
                return Err(OracleError::Shape(format!(
                    "gear entry {i} at +{at:#x} escapes the entry"
                )));
            }
            entries.push((d[at as usize] as i8, u16_at(&d, at as usize + 2)?));
        }
        for cls in 0..3usize {
            per_class[cls] = walk_289e80(&d, g, cls as i8)?;
        }
    }
    Ok(ItemDefinition {
        content_index: ci,
        item_hash,
        world_tag,
        gear,
        entries,
        per_class,
        equip_slot: equip_slot(&d)?,
        stats: stat_list(&d)?,
        curve_offset: curve_offset(&d)?,
        weapon_object: weapon_object(&d)?,
    })
}

/// ⭐ Every content index in the staged inventory, in filename order, then the emblem.
///
/// The Python shelled out to `d1-oracle object --tag 0x80801732 --decode <hex>` once per file and
/// scraped the `+0x0020` line. Here the same decode is [`crate::inventory::read_staged`], in
/// process, through the same client codec - the tool no longer shells out to itself.
///
/// A staged element with no content index (`0xFFFF`) is **skipped with a warning**, exactly as the
/// Python did: it is not an item the card can render, and inventing an index for it is the failure
/// mode this whole table exists to prevent.
pub fn staged_indices(inventory_dir: &Path) -> Result<Vec<u16>> {
    let staged = crate::inventory::read_staged(inventory_dir)?;
    let mut out = Vec::new();
    for e in &staged {
        if e.content_index == crate::inventory::EMPTY_INDEX {
            eprintln!(
                "  ⚠ {}: no +0x24 content index decoded - skipped",
                e.file.file_name().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default()
            );
            continue;
        }
        out.push(e.content_index);
    }
    out.push(EMBLEM_INDEX);
    // De-duplicate, keeping first occurrence - `dict.fromkeys(todo)` in the Python.
    let mut seen = BTreeSet::new();
    out.retain(|ci| seen.insert(*ci));
    Ok(out)
}

/// One TSV row: three per resolved item, one per class.
#[derive(Debug, Clone)]
pub struct Row {
    pub content_index: u16,
    pub item_hash: u32,
    pub world_tag: u32,
    pub class: u8,
    pub arrangement: u16,
    pub equip_slot: u8,
    pub curve_offset: u16,
    pub stats: String,
    /// [`weapon_object`]; `0xFFFF` when the definition has no client record.
    pub weapon_object: u16,
}

/// Expand one resolved definition into its three rows.
pub fn rows_for(def: &ItemDefinition) -> Vec<Row> {
    // 255 = "the definition names no ordinal", which the consumer reads back as `None`.
    let slot = def.equip_slot.unwrap_or(0xFF);
    // '-' = MEASURED as none (`def+0x68` NULL or empty - the constructor writes nothing either
    // way). A row without the column at all is "never measured", and stays distinguishable.
    let stats = match &def.stats {
        Some(v) if !v.is_empty() => {
            v.iter().map(|(k, val)| format!("{k}:{val}")).collect::<Vec<_>>().join(",")
        }
        _ => "-".to_string(),
    };
    (0..3u8)
        .map(|cls| Row {
            content_index: def.content_index,
            item_hash: def.item_hash,
            world_tag: def.world_tag,
            class: cls,
            arrangement: def.per_class[cls as usize].unwrap_or(0xFFFF),
            equip_slot: slot,
            curve_offset: def.curve_offset.1,
            stats: stats.clone(),
            weapon_object: def.weapon_object.unwrap_or(0xFFFF),
        })
        .collect()
}

/// ⭐ Render the TSV byte for byte as it is shipped.
///
/// `index_tsv_sha16` is `sha256` of the **`item-content-index.tsv` file** (not of the entry
/// payload), truncated to 16 hex digits, which is what the provenance line has always carried: it
/// ties this table to the exact index table its content indices were read against.
///
/// ⚠ As with the index table, exactly one line differs from the Python's output on purpose -
/// `# GENERATED by`. See [`crate::item_index::SourceTable::render_tsv`].
pub fn render_tsv(rows: &[Row], index_tsv_sha16: &str, generator: &str) -> String {
    let mut s = String::with_capacity(rows.len() * 64 + 1024);
    s.push_str("# item ART-ARRANGEMENT indices - the u16 at equipment element +0x0C that names the 3D model -\n");
    s.push_str("# and the item's EQUIPPED-ARRAY ORDINAL (def_client+0x18): which of the 20 equipment/equipped\n");
    s.push_str("# entries the item occupies (0x269080 derefs character+0x2B80+slot*8 with it). 255 = none.\n");
    s.push_str(&format!("# GENERATED by {generator} - do not hand-edit.\n"));
    s.push_str("# Walk: FUN_00289E80(def+0x60 gear record, class); def extracted from the packages by\n");
    s.push_str("# world tag; identity-checked against the item hash the entry itself carries at +0x78.\n");
    s.push_str("# 0xFFFF (65535) = NO ARRANGEMENT: FUN_0054B530 rejects -1 on its bounds check -> no geometry.\n");
    s.push_str("# curve_offset: element +0x20's source - *(u16*)(rec+8) of def+0x30's self-relative record,\n");
    s.push_str("# exactly what the client's own constructor FUN_0026E0E0 stores (absent record -> 0 [I]).\n");
    s.push_str("# stats: element +0x88/+0x98's source - def+0x68's stat list, the record FUN_0028B6E0 copies.\n");
    s.push_str("# '-' = MEASURED none (def+0x68 NULL or empty; the constructor writes nothing either way).\n");
    s.push_str(&format!(
        "# provenance: item-content-index.tsv sha256[:16]={index_tsv_sha16}; anchors: ci \
         {GJALLARHORN} -> {GJALLARHORN_ARRANGEMENT} (wildcard), ci {STRIKER}/{BRONZE_TIER} -> NULL \
         gear, ci {EMBLEM_INDEX} equip_slot {EMBLEM_SLOT}, ci {ORYX_MASK} curve_offset \
         {ORYX_MASK_CURVE}.\n"
    ));
    s.push_str("# weapon_object: element +0x0A's source - def_client+0x1C8, the index 0x910C60 resolves through\n");
    s.push_str("# investment_globals+0x350 to the weapon's object-definition tag. 65535 = no client record.\n");
    s.push_str("content_index\titem_hash\tworld_tag\tclass\tarrangement\tequip_slot\tcurve_offset\tstats\tweapon_object\n");
    for r in rows {
        s.push_str(&format!(
            "{}\t{:#010x}\t{:#010x}\t{}\t{}\t{}\t{}\t{}\t{}\n",
            r.content_index,
            r.item_hash,
            r.world_tag,
            r.class,
            r.arrangement,
            r.equip_slot,
            r.curve_offset,
            r.stats,
            r.weapon_object
        ));
    }
    s
}

/// `sha256` of the index TSV **file**, truncated to the 16 hex digits the provenance line carries.
pub fn index_tsv_sha16(path: &Path) -> Result<String> {
    let b = std::fs::read(path)
        .map_err(|e| OracleError::Shape(format!("{}: {e}", path.display())))?;
    Ok(d1_pkg::manifest::sha256_hex(&b)[..16].to_string())
}

/// Build every row for the staged set: [`staged_indices`], resolved in order.
pub fn staged_rows(
    content: &mut Content,
    table: &IndexTable,
    inventory_dir: &Path,
    verbose: bool,
) -> Result<Vec<Row>> {
    let mut rows = Vec::new();
    for ci in staged_indices(inventory_dir)? {
        let def = resolve(content, ci, table)?;
        if verbose {
            println!(
                "ci {:5}  hash {:#010x}  tag {:#010x}  equip_slot {:?}  gear {}  entries {:?}  \
                 per-class {:?}  curve {:?}  stats {:?}",
                def.content_index,
                def.item_hash,
                def.world_tag,
                def.equip_slot,
                def.gear.map(|g| format!("@+{g:#x}")).unwrap_or_else(|| "NULL".into()),
                def.entries,
                def.per_class,
                def.curve_offset,
                def.stats
            );
        }
        rows.extend(rows_for(&def));
    }
    Ok(rows)
}

