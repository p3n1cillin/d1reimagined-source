//! Identifier/number exports from owned 56578 content. No entry payload is written.
//!
//! Package resolution, decompression, vendor rows and item indices use the existing readers.
//! The remaining tag layouts are based on Blam Network gibbon (MIT), widened and checked against
//! the owned PS4 entries; see ATTRIBUTION.md. A table header records every source entry's digest.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use serde_json::{json, Value};

use crate::error::{OracleError, Result};
use crate::oodle::Content;
use crate::vendor_sales::{list, u16_at, u32_at, u64_at};

fn shape(s: impl Into<String>) -> OracleError {
    OracleError::Shape(s.into())
}

/// A typed tag block, using the vendor reader's self-relative list implementation.
fn block(b: &[u8], field: usize, stride: usize, class: u32) -> Result<Vec<usize>> {
    let (n, first) = list(b, field)?;
    if n == 0 {
        return Ok(Vec::new());
    }
    if first < 20
        || u32_at(b, first - 20)? != 0x8080_0184
        || u32_at(b, first - 8)? != class
        || n.checked_mul(stride)
            .and_then(|len| first.checked_add(len))
            .is_none_or(|end| end > b.len())
    {
        return Err(shape(format!(
            "invalid block at {field:#x}, class {class:#x}, stride {stride}"
        )));
    }
    Ok((0..n).map(|i| first + i * stride).collect())
}

fn relative(b: &[u8], field: usize) -> Result<Option<usize>> {
    let rel = u64_at(b, field)? as i64;
    if rel == 0 {
        return Ok(None);
    }
    let at = field
        .checked_add_signed(isize::try_from(rel).map_err(|_| shape("pointer overflow"))?)
        .filter(|at| *at < b.len())
        .ok_or_else(|| shape("pointer escapes the entry"))?;
    Ok(Some(at))
}

fn float(b: &[u8], at: usize) -> Result<f32> {
    let v = f32::from_bits(u32_at(b, at)?);
    if !v.is_finite() {
        return Err(shape("non-finite content number"));
    }
    Ok(v)
}

fn struct_class(b: &[u8], at: usize, class: u32) -> Result<()> {
    // Eight-aligned structs have four bytes of padding after the class word; four-aligned
    // structs (including curves) have the word immediately before the struct.
    if at >= 4 && u32_at(b, at - 4)? == class {
        return Ok(());
    }
    if at >= 8 && u32_at(b, at - 4)? == 0 && u32_at(b, at - 8)? == class {
        return Ok(());
    }
    Err(shape(format!(
        "wrong struct class at {at:#x}, expected {class:#x}"
    )))
}

#[derive(Default)]
struct Sources(BTreeMap<u32, String>);
impl Sources {
    fn read(&mut self, c: &mut Content, tag: u32, class: u32) -> Result<Vec<u8>> {
        let (_, _, actual, b) = c.entry_bytes_for_tag(tag)?;
        if actual != class || u64_at(&b, 0)? != b.len() as u64 {
            return Err(shape(format!(
                "tag {tag:#x}: wrong class or self length ({actual:#x})"
            )));
        }
        self.0.insert(tag, d1_pkg::manifest::sha256_hex(&b));
        Ok(b)
    }
    fn header(&self) -> String {
        let mut s =
            "# GENERATED by d1-oracle content-tables; build 56578.17.04.12.1251.evil\n".to_string();
        for (tag, hash) in &self.0 {
            s.push_str(&format!("# source {tag:#010x} sha256 {hash}\n"));
        }
        s
    }
    fn json(&self, data: Value) -> Value {
        json!({"build":"56578.17.04.12.1251.evil", "generator":"d1-oracle content-tables",
            "sources":self.0.iter().map(|(t,h)| json!({"tag":t,"sha256":h})).collect::<Vec<_>>(), "data":data})
    }
}

fn expressions(b: &[u8], field: usize) -> Result<Vec<Vec<(u8, u32)>>> {
    block(b, field, 16, 0x8080_16E4)?
        .into_iter()
        .map(|e| {
            block(b, e, 8, 0x8080_1776)?
                .into_iter()
                .map(|o| {
                    let op = b[o];
                    if !(1..=21).contains(&op) {
                        return Err(shape(format!("unknown unlock opcode {op}")));
                    }
                    Ok((op, u32_at(b, o + 4)?))
                })
                .collect()
        })
        .collect()
}

fn program(expr: &[Vec<(u8, u32)>]) -> String {
    expr.iter()
        .map(|e| {
            e.iter()
                .map(|(op, n)| format!("{op}:{n}"))
                .collect::<Vec<_>>()
                .join(",")
        })
        .collect::<Vec<_>>()
        .join(";")
}

/// Render all launch programs and preserve the distinct launch/join/visibility gates separately.
fn activities(c: &mut Content) -> Result<BTreeMap<String, String>> {
    let mut src = Sources::default();
    let root = src.read(c, 0x80A5_8001, 0x8080_1750)?;
    let rules = src.read(c, u32_at(&root, 0x28)?, 0x8080_1864)?;
    let mut groups = BTreeMap::new();
    for r in block(&rules, 0x30, 40, 0x8080_1778)? {
        let hash = u32_at(&rules, r + 32)?;
        if groups
            .insert(
                hash,
                [expressions(&rules, r)?, expressions(&rules, r + 16)?],
            )
            .is_some()
        {
            return Err(shape("duplicate unlock group"));
        }
    }
    let b = src.read(c, u32_at(&root, 0x48)?, 0x8080_1915)?;
    let unlocks: BTreeSet<_> = block(&b, 0x88, 48, 0x8080_177B)?.into_iter().collect();
    let mut rows = Vec::new();
    let mut tsv = String::new();
    for (index, r) in block(&b, 8, 16, 0x8080_18A7)?.into_iter().enumerate() {
        let def = relative(&b, r + 8)?.ok_or_else(|| shape("activity missing its definition"))?;
        if u32_at(&b, r)? != u32_at(&b, def)? {
            return Err(shape("activity identity mismatch"));
        }
        let mut gates = [Vec::new(), Vec::new(), Vec::new()];
        let mut ids = Vec::new();
        for at in block(&b, def + 8, 4, 0x8080_0070)? {
            let id = u32_at(&b, at)?;
            let g = groups
                .get(&id)
                .ok_or_else(|| shape(format!("unresolved unlock group {id:#x}")))?;
            ids.push(id);
            gates[0].extend(g[0].clone());
            gates[1].extend(g[1].clone());
        }
        if let Some(u) = relative(&b, def + 0x40)? {
            if !unlocks.contains(&u) {
                return Err(shape(
                    "activity unlock pointer is not an unlock-array member",
                ));
            }
            for (k, gate) in gates.iter_mut().enumerate() {
                gate.extend(expressions(&b, u + k * 16)?);
            }
        }
        tsv.push_str(&format!("{index}\t{}\n", program(&gates[0])));
        let mut options = Vec::new();
        for o in block(&b, def + 0x78, 40, 0x8080_19A4)? {
            let tokens: Vec<_> = block(&b, o, 8, 0x8080_1776)?
                .into_iter()
                .map(|at| Ok((b[at], u32_at(&b, at + 4)?)))
                .collect::<Result<_>>()?;
            options.push(json!({"requirement":tokens,"tag":u32_at(&b,o+16)?}));
        }
        rows.push(json!({"index":index, "hash":u32_at(&b,r)?, "groups":ids,
            "launch":gates[0], "join":gates[1], "visible":gates[2],
            "options":u32_at(&b,def+0x88)?,"option_sets":options}));
    }
    Ok(BTreeMap::from([
        ("characters/activity-rules.tsv".into(), src.header() + &tsv),
        (
            "characters/activity-rule-programs.json".into(),
            render_json(&src.json(json!(rows))),
        ),
    ]))
}

fn vendors(c: &mut Content) -> Result<(String, String)> {
    let mut src = Sources::default();
    let b = src.read(c, crate::vendor_sales::VENDOR_TABLE_TAG, 0x8080_193B)?;
    let mut all = "index\thash\ttag\n".to_string();
    let mut roles = "role\tindex\thash\n".to_string();
    for v in crate::vendor_sales::parse_vendor_table(&b)? {
        all.push_str(&format!("{}\t{}\t{}\n", v.index, v.hash, v.tag));
        let role = match v.hash {
            892630493 => "vault",
            2021251983 | 2762206170 => "postmaster",
            _ => continue,
        };
        roles.push_str(&format!("{role}\t{}\t{}\n", v.index, v.hash));
    }
    Ok((src.header() + &all, src.header() + &roles))
}

fn progressions(c: &mut Content) -> Result<String> {
    let mut src = Sources::default();
    let root = src.read(c, 0x80A5_8001, 0x8080_1750)?;
    let b = src.read(c, u32_at(&root, 0x338)?, 0x8080_1779)?;
    let mut text = "index\thash\n".to_string();
    let mut hashes = BTreeSet::new();
    for (index, at) in block(&b, 8, 56, 0x8080_16E3)?.into_iter().enumerate() {
        let hash = u32_at(&b, at)?;
        if !hashes.insert(hash) {
            return Err(shape("duplicate progression hash"));
        }
        text.push_str(&format!("{index}\t{hash}\n"));
    }
    Ok(src.header() + &text)
}

/// Grid ordinals are positions in the 56578 table, not definition tags or manifest order.
fn talent_grid_rows(b: &[u8]) -> Result<Vec<(u16, u32)>> {
    let mut hashes = BTreeSet::new();
    block(b, 8, 24, 0x8080_17CB)?
        .into_iter()
        .enumerate()
        .map(|(index, at)| {
            let index = u16::try_from(index)
                .ok()
                .filter(|i| *i != u16::MAX)
                .ok_or_else(|| shape("talent-grid index reaches reserved absent value"))?;
            let hash = u32_at(b, at)?;
            if !hashes.insert(hash) {
                return Err(shape("duplicate talent-grid hash"));
            }
            Ok((index, hash))
        })
        .collect()
}

fn talent_grids(c: &mut Content) -> Result<String> {
    let mut src = Sources::default();
    let b = src.read(c, 0x80A5_E227, 0x8080_18C2)?;
    let mut text = "index\thash\n".to_string();
    for (index, hash) in talent_grid_rows(&b)? {
        text.push_str(&format!("{index}\t{hash}\n"));
    }
    Ok(src.header() + &text)
}

fn starting_kit(
    c: &mut Content,
    items: &crate::item_index::SourceTable,
) -> Result<(String, String)> {
    let mut src = Sources::default();
    src.0.insert(0x80A5_FFBE, items.source_sha256());
    let root = src.read(c, 0x80A5_8001, 0x8080_1750)?;
    let b = src.read(c, u32_at(&root, 0xE8)?, 0x8080_190D)?;
    let mut rows = Vec::new();
    let mut text = String::new();
    for at in block(&b, 0x18, 40, 0x8080_18C9)? {
        let class = b[at];
        let mut lists = Vec::new();
        for f in [at + 8, at + 24] {
            let mut list = Vec::new();
            for r in block(&b, f, 2, 0x8080_432F)? {
                let index = u16_at(&b, r)?;
                let &(hash, _, tag) = items
                    .rows
                    .get(index as usize)
                    .ok_or_else(|| shape("kit index outside item table"))?;
                let (_, _, _, def) = c.entry_bytes_for_tag(tag)?;
                src.0.insert(tag, d1_pkg::manifest::sha256_hex(&def));
                let storage = crate::vendor_sales::parse_storage(&def)?;
                list.push(json!({"index":index,"hash":hash,"bucket":storage.bucket,"instanced":storage.instanced}));
            }
            lists.push(list);
        }
        // Keep both lists named by their fields until their distinct creation roles are established.
        text.push_str(&format!(
            "{class}\t{}\n",
            lists[0]
                .iter()
                .map(|v| format!("{:02x}:{}", v["bucket"].as_u64().unwrap(), v["index"]))
                .collect::<Vec<_>>()
                .join(",")
        ));
        rows.push(json!({"class":class,"items":lists[0],"alternate_items":lists[1]}));
    }
    Ok((
        src.header()
            + "# First default-gear preload list; using this as a server grant is not verified.\n"
            + &text,
        render_json(&src.json(json!(rows))),
    ))
}

fn stat_curves(c: &mut Content) -> Result<Value> {
    let mut src = Sources::default();
    let b = src.read(c, crate::native_item_stat::STAT_TABLE_TAG, 0x8080_17EC)?;
    let mut rows = Vec::new();
    for (index, r) in block(&b, 8, 16, 0x8080_1870)?.into_iter().enumerate() {
        let mut points = Vec::new();
        let mut quality = Vec::new();
        let mut weights = Vec::new();
        if let Some(curve) = relative(&b, r + 8)? {
            struct_class(&b, curve, 0x8080_173D)?;
            for p in block(&b, curve, 8, 0x8080_46EA)? {
                points.push([u32_at(&b, p)? as i32, u32_at(&b, p + 4)? as i32]);
            }
            for p in block(&b, curve + 16, 8, 0x8080_4731)? {
                quality.push(json!([u32_at(&b, p)? as i32, float(&b, p + 4)?]));
            }
            for p in block(&b, curve + 32, 4, 0x8080_4698)? {
                weights.push([u16_at(&b, p)?, u16_at(&b, p + 2)?]);
            }
        }
        rows.push(
            json!({"index":index,"hash":u32_at(&b,r)?,"flags":u32_at(&b,r+4)?,
            "points":points,"quality_points":quality,"slot_weights":weights}),
        );
    }
    Ok(src.json(json!(rows)))
}

fn infusion(c: &mut Content) -> Result<String> {
    let mut src = Sources::default();
    let root = src.read(c, 0x80A5_8001, 0x8080_1750)?;
    let b = src.read(c, u32_at(&root, 0x298)?, 0x8080_17C1)?;
    let mut text = "# Selected by target definition +0x8A (tier), via 56578 0x26F400 -> interface +0x428.\n# floor_curve_index is sampled on the Attack quality curve; it is not a literal gain.\nindex\ttier_hash\trate\tfloor_curve_index\n".to_string();
    for (i, p) in block(&b, 8, 12, 0x8080_18EC)?.into_iter().enumerate() {
        text.push_str(&format!(
            "{i}\t{}\t{}\t{}\n",
            u32_at(&b, p)?,
            float(&b, p + 4)?,
            u16_at(&b, p + 8)? as i16
        ));
    }
    Ok(src.header() + &text)
}

fn tags_of_class(c: &Content, class: u32) -> Result<Vec<u32>> {
    let ids: BTreeSet<_> = c
        .estate()
        .packages
        .iter()
        .filter(|p| p.locale() == 0)
        .map(|p| p.id())
        .collect();
    let mut tags = Vec::new();
    for id in ids {
        let p = &c.estate().packages[c.newest_index(id)?];
        tags.extend(
            p.entries()
                .filter(|e| e.class_tag == class)
                .map(|e| d1_pkg::make_tag(id, e.index)),
        );
    }
    Ok(tags)
}

fn scoreboard_program(b: &[u8], code: usize, constants: usize, vars: usize) -> Result<Value> {
    let code: Vec<_> = block(b, code, 1, 0x8080_0009)?
        .into_iter()
        .map(|at| b[at])
        .collect();
    let constants: Vec<_> = block(b, constants, 4, 0x8080_0090)?
        .into_iter()
        .map(|at| float(b, at))
        .collect::<Result<_>>()?;
    let vars: Vec<_> = block(b, vars, 4, 0x8080_0070)?
        .into_iter()
        .map(|at| u32_at(b, at))
        .collect::<Result<_>>()?;
    Ok(json!({"bytecode":code,"consts":constants,"vars":vars}))
}

/// Preserve every incident/stat program; mode associations and match limits are separate content.
fn scoreboards(c: &mut Content) -> Result<Value> {
    let mut src = Sources::default();
    let mut rows = Vec::new();
    for tag in tags_of_class(c, 0x8080_099C)? {
        let b = src.read(c, tag, 0x8080_099C)?;
        let mut rules = Vec::new();
        for r in block(&b, 0x80, 80, 0x8080_03DA)? {
            let mut rule = scoreboard_program(&b, r + 16, r + 32, r + 64)?;
            rule["incident_name"] = json!(u32_at(&b, r)?);
            rule["audience"] = json!(u32_at(&b, r + 4)?);
            rule["stat_name"] = json!(u32_at(&b, r + 8)?);
            rule["flags"] = json!(b[r + 13]);
            rules.push(rule);
        }
        let mut derived = Vec::new();
        for r in block(&b, 0x70, 72, 0x8080_03E7)? {
            let mut rule = scoreboard_program(&b, r + 8, r + 24, r + 56)?;
            rule["stat_name"] = json!(u32_at(&b, r)?);
            rule["flags"] = json!(b[r + 4]);
            derived.push(rule);
        }
        rows.push(json!({"tag":tag,"rules":rules,"derived_stats":derived}));
    }
    Ok(src.json(json!(rows)))
}

/// All typed activity-option overrides. Their values do not establish a mode's defaults.
fn activity_options(c: &mut Content) -> Result<Value> {
    let mut src = Sources::default();
    let mut rows = Vec::new();
    for tag in tags_of_class(c, 0x8080_182E)? {
        let b = src.read(c, tag, 0x8080_182E)?;
        let mut values = Vec::new();
        for at in block(&b, 8, 8, 0x8080_0408)? {
            let p = relative(&b, at)?.ok_or_else(|| shape("null activity option"))?;
            let kind = u32_at(&b, p - 4)?;
            let value = match kind {
                0x8080_0347 => json!(u32_at(&b, p + 4)? as i32),
                0x8080_08CC => json!(float(&b, p + 4)?),
                0x8080_07CB => json!(
                    b.get(p + 4)
                        .copied()
                        .ok_or_else(|| shape("short boolean option"))?
                        != 0
                ),
                // The last four classes are packed enum words in 56578. Preserve their type
                // and value; do not assign names from the older build's enums.
                0x8080_034C | 0x8080_0D7B | 0x8080_41BE | 0x8080_4726 | 0x8080_46D7
                | 0x8080_46BB => json!(u32_at(&b, p + 4)?),
                0x8080_0443 => json!((0..4)
                    .map(|i| u32_at(&b, p + 4 + i * 4))
                    .collect::<Result<Vec<_>>>()?),
                0x8080_07EE => json!(b
                    .get(p + 4..p + 20)
                    .ok_or_else(|| shape("short integer option array"))?
                    .to_vec()),
                _ => return Err(shape(format!("unknown activity-option class {kind:#x}"))),
            };
            values.push(json!({"name_hash":u32_at(&b,p)?,"type":kind,"value":value}));
        }
        rows.push(json!({"tag":tag,"options":values}));
    }
    Ok(src.json(json!(rows)))
}

/// Compute all outputs before writing any file. `root` is a fixture directory, not private storage.
pub fn export(c: &mut Content) -> Result<BTreeMap<String, String>> {
    let image = d1_eboot::image::Image::open_default().map_err(|e| shape(e.to_string()))?;
    if image.sha256() != crate::weapon_stats::MEASURED_EBOOT_SHA256 {
        return Err(shape("content exports require the owned 56578 executable"));
    }
    let (_, _, class, b) = c.entry_bytes_for_tag(0x80A5_FFBE)?;
    if class != crate::item_index::SOURCE_ENTRY_CLASS {
        return Err(shape("wrong item index class"));
    }
    let items = crate::item_index::SourceTable::parse(b)?;
    if items.count != crate::item_index::SOURCE_56578.count {
        return Err(shape("wrong build's item table"));
    }
    let mut out = activities(c)?;
    out.insert(
        "activities/scoreboard-definitions.json".into(),
        render_json(&scoreboards(c)?),
    );
    out.insert(
        "activities/activity-options.json".into(),
        render_json(&activity_options(c)?),
    );
    out.insert(
        "items/item-content-index.tsv".into(),
        items.render_tsv("d1-oracle content-tables"),
    );
    let (all, roles) = vendors(c)?;
    out.insert("vendor/vendor-index.tsv".into(), all);
    out.insert("vendor/vendor-roles.tsv".into(), roles);
    out.insert("progression/progression-index.tsv".into(), progressions(c)?);
    out.insert("items/talent-grid-index.tsv".into(), talent_grids(c)?);
    let (kit, detail) = starting_kit(c, &items)?;
    out.insert("characters/starting-kit.tsv".into(), kit);
    out.insert("characters/starting-kit-lists.json".into(), detail);
    out.insert(
        "items/stat-curves.json".into(),
        render_json(&stat_curves(c)?),
    );
    out.insert("items/infusion.tsv".into(), infusion(c)?);
    Ok(out)
}

/// One data row per line keeps numeric programs reviewable without thousands of array lines.
fn render_json(value: &Value) -> String {
    let mut meta = value.clone();
    let rows = meta.as_object_mut().unwrap().remove("data").unwrap();
    let mut s = serde_json::to_string_pretty(&meta).unwrap();
    s.truncate(s.rfind('}').unwrap());
    s = s.trim_end().to_string();
    s.push_str(",\n  \"data\": [\n");
    let rows = rows.as_array().unwrap();
    for (i, row) in rows.iter().enumerate() {
        s.push_str("    ");
        s.push_str(&serde_json::to_string(row).unwrap());
        if i + 1 < rows.len() {
            s.push(',');
        }
        s.push('\n');
    }
    s.push_str("  ]\n}\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn block_bounds_and_header_class_are_required() {
        let mut b = vec![0; 80];
        b[0..8].copy_from_slice(&2u64.to_le_bytes());
        b[8..16].copy_from_slice(&24u64.to_le_bytes());
        b[28..32].copy_from_slice(&0x8080_0184u32.to_le_bytes());
        b[32..40].copy_from_slice(&2u64.to_le_bytes());
        b[40..44].copy_from_slice(&0x8080_0070u32.to_le_bytes());
        assert_eq!(block(&b, 0, 4, 0x8080_0070).unwrap(), [48, 52]);
        assert!(block(&b, 0, 4, 0x8080_0009).is_err());
        assert!(block(&b[..52], 0, 4, 0x8080_0070).is_err());
        b[8..16].copy_from_slice(&(-32i64).to_le_bytes());
        assert!(block(&b, 0, 4, 0x8080_0070).is_err());
    }

    #[test]
    fn talent_grid_indices_follow_rows_and_reject_ambiguous_or_short_tables() {
        let mut b = vec![0; 48 + 2 * 24];
        b[8..16].copy_from_slice(&2u64.to_le_bytes());
        b[16..24].copy_from_slice(&16u64.to_le_bytes());
        b[28..32].copy_from_slice(&0x8080_0184u32.to_le_bytes());
        b[32..40].copy_from_slice(&2u64.to_le_bytes());
        b[40..44].copy_from_slice(&0x8080_17CBu32.to_le_bytes());
        b[48..52].copy_from_slice(&99u32.to_le_bytes());
        b[72..76].copy_from_slice(&12u32.to_le_bytes());
        assert_eq!(talent_grid_rows(&b).unwrap(), [(0, 99), (1, 12)]);
        assert!(talent_grid_rows(&b[..b.len() - 1]).is_err());
        b[72..76].copy_from_slice(&99u32.to_le_bytes());
        assert!(talent_grid_rows(&b).is_err());
    }

    #[test]
    fn owned_56578_exports_match_every_committed_table() {
        let Some(eboot) = std::env::var_os("D1_EBOOT") else {
            eprintln!("SKIP: set D1_EBOOT to the owned 56578 executable");
            return;
        };
        let Some(repo) = std::env::var_os("D1_REPO") else {
            eprintln!("SKIP: set D1_REPO to the repository root");
            return;
        };
        if !crate::oodle::default_pkgdir().is_dir() {
            eprintln!("SKIP: owned packages absent; set D1_PKGDIR");
            return;
        }
        assert!(Path::new(&eboot).is_file());
        let mut c = Content::open_default().unwrap();
        let out = export(&mut c).unwrap();
        assert_eq!(out.len(), 13);
        for (name, expected) in out {
            let path = Path::new(&repo).join("ps4/fixtures/56578").join(&name);
            assert_eq!(
                std::fs::read_to_string(path).unwrap().replace("\r\n", "\n"),
                expected,
                "{name}"
            );
        }
    }
}

pub fn write(c: &mut Content, root: &Path) -> Result<()> {
    let tables = export(c)?;
    for (name, text) in tables {
        let path = root.join(&name);
        std::fs::create_dir_all(path.parent().unwrap()).map_err(|e| shape(e.to_string()))?;
        std::fs::write(&path, &text).map_err(|e| shape(e.to_string()))?;
        println!(
            "{name}: {} data lines",
            text.lines().filter(|l| !l.starts_with('#')).count()
        );
    }
    Ok(())
}
